\echo '=== FOUR WAYS TO DEFINE A PRIMARY KEY ==='

-- 1. Column-level primary key.
CREATE TABLE lab07.column_key (
    mentor_id INTEGER PRIMARY KEY,
    mentor_name VARCHAR(80) NOT NULL
);

-- 2. Table-level primary key.
CREATE TABLE lab07.table_key (
    workshop_id INTEGER,
    workshop_title VARCHAR(100) NOT NULL,
    PRIMARY KEY (workshop_id)
);

-- 3. Named primary-key constraint.
CREATE TABLE lab07.named_key (
    center_id INTEGER,
    center_name VARCHAR(100) NOT NULL,
    CONSTRAINT pk_learning_center PRIMARY KEY (center_id)
);

-- 4. Adding a primary key to an existing table.
CREATE TABLE lab07.added_key (
    room_id INTEGER NOT NULL,
    room_label VARCHAR(40) NOT NULL
);

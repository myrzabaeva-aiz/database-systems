\echo '=== COMPOSITE KEY RESULTS ==='
SELECT participant_id, workshop_code, cohort, registration_status
FROM lab07.workshop_registration
ORDER BY participant_id, workshop_code, cohort;

\echo '=== GENERATED ID RESULTS ==='
SELECT 'SERIAL' AS method, material_id::BIGINT AS id,
       material_name AS example
FROM lab07.materials
UNION ALL
SELECT 'BIGSERIAL', contribution_id, donor_label
FROM lab07.contributions
UNION ALL
SELECT 'IDENTITY ALWAYS', reservation_id::BIGINT, participant_name
FROM lab07.seat_reservations
UNION ALL
SELECT 'IDENTITY BY DEFAULT', partner_id::BIGINT, partner_name
FROM lab07.community_partners
ORDER BY method, id;

\echo '=== AUTO-CREATED PRIMARY KEY INDEXES ==='
SELECT tablename, indexname, indexdef
FROM pg_indexes
WHERE schemaname = 'lab07'
  AND tablename IN ('column_key', 'workshop_registration')
ORDER BY tablename, indexname;


-- PL/pgSQL catches EXPECTED database errors, so the rest of the lab runs.
DO $$
BEGIN
    BEGIN
        INSERT INTO lab07.column_key VALUES (11, 'Duplicate mentor');
        RAISE EXCEPTION 'FAIL: duplicate primary-key value was accepted';
    EXCEPTION WHEN unique_violation THEN
        RAISE NOTICE 'PASS: PRIMARY KEY rejected a duplicate ID';
    END;

    BEGIN
        INSERT INTO lab07.column_key VALUES (NULL, 'Missing mentor ID');
        RAISE EXCEPTION 'FAIL: NULL primary-key value was accepted';
    EXCEPTION WHEN not_null_violation THEN
        RAISE NOTICE 'PASS: PRIMARY KEY rejected NULL';

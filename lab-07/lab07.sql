\echo '=== COMPOSITE PRIMARY KEY ==='

-- A participant can attend the same workshop in another cohort,
-- but may register only once in one specific cohort.
CREATE TABLE lab07.workshop_registration (
    participant_id INTEGER NOT NULL,
    workshop_code VARCHAR(16) NOT NULL,
    cohort VARCHAR(20) NOT NULL,
    registration_status VARCHAR(20) NOT NULL DEFAULT 'registered',
    CONSTRAINT pk_workshop_registration
        PRIMARY KEY (participant_id, workshop_code, cohort)
);


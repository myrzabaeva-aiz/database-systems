\echo '=== GENERATED IDENTIFIERS ==='

-- SERIAL creates a regular integer column backed by a sequence.
CREATE TABLE lab07.materials (
    material_id SERIAL PRIMARY KEY,
    material_name VARCHAR(80) NOT NULL
);

-- BIGSERIAL supports a much larger range of generated IDs.
CREATE TABLE lab07.contributions (
    contribution_id BIGSERIAL PRIMARY KEY,
    donor_label VARCHAR(80) NOT NULL,
    amount NUMERIC(10,2) NOT NULL
);

-- GENERATED ALWAYS normally refuses manually supplied IDs.
CREATE TABLE lab07.seat_reservations (
    reservation_id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    participant_name VARCHAR(80) NOT NULL
);

-- GENERATED BY DEFAULT allows explicit IDs too.
CREATE TABLE lab07.community_partners (
    partner_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    partner_name VARCHAR(80) NOT NULL
);

